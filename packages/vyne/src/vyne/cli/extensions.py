# Generation
# ---------------------------------------------------------------------------

def registrant_content(extensions: list[Extension]) -> str:
    """The generated Kotlin registrant for the given extensions."""
    calls = "\n".join(
        f"    {ext.android_register}.register(context, registry)"
        for ext in extensions
    )
    if calls:
        calls += "\n"
    surface_calls = "\n".join(
        f"    ({ext.android_register} as? SurfaceRegistrant)"
        f"?.registerSurfaces(registry)"
        for ext in extensions
    )
    if surface_calls:
        surface_calls += "\n"
    return f"""/** Generated by the Vyne CLI. DO NOT EDIT. */
package dev.vyne.generated

import android.content.Context
import dev.vyne.ElementRegistry
import dev.vyne.RenderSurfaceRegistry
import dev.vyne.SurfaceRegistrant

internal fun registerAppExtensions(
    context: Context,
    registry: ElementRegistry,
) {{
{calls}}}

internal fun registerAppSurfaces(
    registry: RenderSurfaceRegistry,
) {{
{surface_calls}}}
"""


def registrant_target(project: Any) -> Path:
    """The registrant file path for the project mode.

    The app module owns the generated file (the packaged host excludes its
    shipped default); the checkout host regenerates its own in place.
    """
    if project.generated:
        return (
            project.root / "android" / "app" / "src" / "main" / "java"
            / "dev" / "vyne" / "generated" / REGISTRANT_RELATIVE
        )
    return (
        project.root / "android" / "host" / "src" / "main" / "java"
        / "dev" / "vyne" / "generated" / REGISTRANT_RELATIVE
    )


def generate_extension_files(project: Any, extensions: list[Extension]) -> None:
    """Journaled generation of the registrant.

    Written through the durable generation transaction; byte-identical
    content skips the write (no churn on unchanged builds).
    """
    registrant_path = registrant_target(project)
    builder = PlanBuilder(project.root)
    builder.add_file(
        os.path.relpath(registrant_path, project.root),
        registrant_content(extensions),
        policy=ConflictPolicy.REPLACE,
    )
    plan = builder.preflight()
    plan.apply()
    plan.cleanup()
